// Generates supabase/seed.sql from src/data/seed.js so the DB and demo catalogue stay in sync.
import { writeFileSync } from 'node:fs';
import { seedCategories, seedProducts } from '../src/data/seed.js';

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;

let sql = '-- Generated by scripts/generate-seed.mjs. Run after schema.sql.\n';
for (const c of seedCategories)
  sql += `insert into public.categories (slug,name,image_url,blurb,sort_order) values (${q(c.slug)},${q(c.name)},${q(c.image)},${q(c.blurb)},${c.sort}) on conflict (slug) do nothing;\n`;
for (const p of seedProducts)
  sql += `insert into public.products (slug,name,category_id,price,compare_at_price,description,image_url,stock,is_bestseller,is_new,rating,review_count,sold,finish,size,tags,created_at) values (${q(p.slug)},${q(p.name)},(select id from public.categories where slug=${q(p.categoryId)}),${p.price},${p.compareAt},${q(p.description)},${q(p.image)},${p.stock},${p.isBestseller},${p.isNew},${p.rating},${p.reviewCount},${p.sold},${q(p.finish)},${q(p.size)},${arr(p.tags)},${q(p.createdAt)}) on conflict (slug) do nothing;\n`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`Wrote supabase/seed.sql (${seedCategories.length} categories, ${seedProducts.length} products)`);
